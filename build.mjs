// Builds the site into dist/:
// - site/ (the page, styles, scripts),
// - MapLibre's CSP-safe build and the self-hosted fonts, copied from npm so no visitor loads
//   anything from a CDN or Google,
// - data/sweden/ (written weekly by scripts/build-data.mjs: an index and one file per map square)
//   as /data/sweden/. Before the first run it falls back to data/sample/ so the page still builds.
import { cpSync, mkdirSync, rmSync, copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'

// One person-made, openly licensed icon per setting, from Lucide (ISC licence, credited on the
// About page). Written into /icons.js so the map pins and placeholders need no extra requests.
const ICONS = { nature: 'trees', water: 'waves', urban: 'tree-deciduous', squares: 'landmark', gardens: 'flower-2', view: 'binoculars', libraries: 'book-open' }

const FONTS = [
  ['fraunces', [500]],
  ['instrument-sans', [400, 500, 600]],
]

rmSync('dist', { recursive: true, force: true })
cpSync('site', 'dist', { recursive: true })

mkdirSync('dist/vendor', { recursive: true })
for (const f of ['maplibre-gl-csp.js', 'maplibre-gl-csp-worker.js', 'maplibre-gl.css', 'LICENSE.txt']) {
  copyFileSync(`node_modules/maplibre-gl/dist/${f}`, `dist/vendor/${f === 'LICENSE.txt' ? 'maplibre-LICENSE.txt' : f}`)
}

mkdirSync('dist/fonts', { recursive: true })
for (const [family, weights] of FONTS) {
  for (const w of weights) {
    const file = `${family}-latin-${w}-normal.woff2`
    copyFileSync(`node_modules/@fontsource/${family}/files/${file}`, `dist/fonts/${file}`)
  }
}

const icons = {}
for (const [setting, name] of Object.entries(ICONS)) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8')
  icons[setting] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim()
}
writeFileSync('dist/icons.js', `// Generated by build.mjs from lucide-static (ISC, https://lucide.dev). Inner SVG of each 24x24 icon.\nwindow.EM_ICONS = ${JSON.stringify(icons, null, 1)}\n`)
copyFileSync('node_modules/lucide-static/LICENSE', 'dist/vendor/lucide-LICENSE.txt')

// The places: data/sweden/ (written weekly), or the small offline sample before the first run.
const data = existsSync('data/sweden/index.json') ? 'data/sweden' : 'data/sample'
cpSync(data, 'dist/data/sweden', { recursive: true })
console.log(`Built dist/ with ${data}`)
